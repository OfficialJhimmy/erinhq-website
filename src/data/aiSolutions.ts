export function getSolutionBySlug(slug: string): AISolution | undefined {
  return aiSolutions.find((solution) => solution.slug === slug);
}

export function getRelatedSolutions(current: AISolution, limit = 3): AISolution[] {
  const sameCategory = aiSolutions.filter(
    (solution) => solution.slug !== current.slug && solution.category === current.category
  );
  if (sameCategory.length >= limit) return sameCategory.slice(0, limit);

  const others = aiSolutions.filter(
    (solution) => solution.slug !== current.slug && solution.category !== current.category
  );
  return [...sameCategory, ...others].slice(0, limit);
}
